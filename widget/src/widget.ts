// ------------------------------------------------------------ helpers

function el<K extends keyof HTMLElementTagNameMap>(tag: K, attrs: Record<string, string> = {}, html = ""): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  if (html) node.innerHTML = html;
  return node;
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
}

/** Minimal, safe Markdown: escape first, then bold, links and bullet lists. */
function renderText(text: string): string {
  const inline = (s: string) =>
    escapeHtml(s)
      .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
      .replace(/(https?:\/\/[^\s<]+[^\s<.,;:!?)])/g, '<a href="$1" target="_blank" rel="noopener">$1</a>');
  const out: string[] = [];
  let list: string[] = [];
  const flushList = () => {
    if (list.length) out.push(`<ul>${list.map((li) => `<li>${inline(li)}</li>`).join("")}</ul>`);
    list = [];
  };
  for (const line of text.split("\n")) {
    const item = line.match(/^\s*(?:[-*•]|\d+[.)])\s+(.*)/);
    if (item) list.push(item[1]);
    else {
      flushList();
      if (line.trim()) out.push(`<p>${inline(line)}</p>`);
    }
  }
  flushList();
  return out.join("");
}

function storage(): Storage | null {
  try {
    return window.sessionStorage;
  } catch {
    return null;
  }
}

// ------------------------------------------------------------ widget

class SiteAssistant {
  private shadow: ShadowRoot;
  private root: HTMLDivElement;
  private config!: SiteConfig;
  private t = TEXTS.fr;
  private panel: HTMLDivElement | null = null;
  private msgs!: HTMLDivElement;
  private input!: HTMLTextAreaElement;
  private sendBtn!: HTMLButtonElement;
  private chips!: HTMLDivElement;
  private launcher!: HTMLButtonElement;
  private busy = false;
  private conversationId: string | null = null;
  private history: StoredMessage[] = [];
  private storageKey: string;

  constructor(private api: string, private siteId: string, private teaser: boolean, theme: string) {
    const host = document.createElement("div");
    host.id = "site-assistant";
    document.body.appendChild(host);
    this.shadow = host.attachShadow({ mode: "open" });
    this.shadow.appendChild(el("style", {}, css));
    this.root = el("div", { class: `root ${theme === "dark" || theme === "auto" ? theme : ""}` });
    this.shadow.appendChild(this.root);
    this.storageKey = `site-assistant:${siteId}`;
  }

  private ready: Promise<boolean> = Promise.resolve(false);

  /** Shows the button at once; the site settings load in the background. Fetching
   * them also wakes up a server that was asleep, while the visitor reads the page. */
  start(color?: string) {
    if (color) this.root.style.setProperty("--c", color);
    this.restore();
    this.launcher = el("button", { class: "launcher", "aria-label": this.t.open, "aria-expanded": "false" }, ICON_CHAT);
    this.launcher.addEventListener("click", () => this.toggle());
    this.root.appendChild(this.launcher);

    this.ready = this.loadConfig();
    this.ready.then((ok) => {
      if (!ok) this.launcher.remove();
      else if (this.teaser && !this.history.length) window.setTimeout(() => this.showTeaser(), 3500);
    });
  }

  private async loadConfig(): Promise<boolean> {
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        const res = await fetch(`${this.api}/api/sites/${encodeURIComponent(this.siteId)}/config`);
        if (res.ok) {
          this.config = await res.json();
          this.t = this.config.language === "en" ? TEXTS.en : TEXTS.fr;
          this.root.style.setProperty("--c", this.config.color);
          this.launcher.setAttribute("aria-label", this.t.open);
          return true;
        }
        if (res.status === 403 || res.status === 404) {
          console.warn(`[site-assistant] site "${this.siteId}" is not available here (${res.status})`);
          return false;
        }
      } catch {
        /* server waking up or network hiccup: retry */
      }
      await new Promise((r) => window.setTimeout(r, 2000));
    }
    return false;
  }

  // ---------------------------------------------------------- state

  private restore() {
    try {
      const saved = JSON.parse(storage()?.getItem(this.storageKey) || "null");
      if (saved) {
        this.conversationId = saved.conversationId;
        this.history = saved.history || [];
      }
    } catch {
      /* corrupted or unavailable storage: start fresh */
    }
  }

  private save() {
    try {
      storage()?.setItem(this.storageKey, JSON.stringify({ conversationId: this.conversationId, history: this.history.slice(-30) }));
    } catch {
      /* storage full or blocked: the chat still works for this page */
    }
  }

  // ---------------------------------------------------------- open / close

  private showTeaser() {
    if (this.panel) return;
    const teaser = el("div", { class: "teaser", role: "status" });
    const open = el("button", { class: "open" });
    open.textContent = this.t.teaser;
    open.addEventListener("click", () => {
      teaser.remove();
      this.toggle();
    });
    const x = el("button", { class: "x", "aria-label": this.t.close }, "×");
    x.addEventListener("click", () => teaser.remove());
    teaser.append(open, x);
    this.root.appendChild(teaser);
  }

  private async toggle() {
    this.root.querySelector(".teaser")?.remove();
    if (this.panel) {
      this.panel.remove();
      this.panel = null;
      this.launcher.setAttribute("aria-expanded", "false");
      this.launcher.focus();
      return;
    }
    if (!this.config) {
      // Clicked while the server is still waking up: show progress, then open.
      this.launcher.classList.add("loading");
      this.launcher.setAttribute("aria-busy", "true");
      const ok = await this.ready;
      this.launcher.classList.remove("loading");
      this.launcher.removeAttribute("aria-busy");
      if (!ok || this.panel) return;
    }
    this.buildPanel();
    this.launcher.setAttribute("aria-expanded", "true");
    this.input.focus();
  }

  private buildPanel() {
    const panel = el("div", { class: "panel", role: "dialog", "aria-label": this.config.name });
    const head = el("div", { class: "head" });
    head.innerHTML = `
      <div class="avatar">${escapeHtml(this.config.name.charAt(0))}</div>
      <div><div class="title">${escapeHtml(this.config.name)}</div>
      <div class="sub"><span class="dot"></span>${escapeHtml(this.t.subtitle)}</div></div>`;
    const close = el("button", { class: "close", "aria-label": this.t.close }, "×");
    close.addEventListener("click", () => this.toggle());
    head.appendChild(close);

    this.msgs = el("div", { class: "msgs", "aria-live": "polite" });
    this.chips = el("div", { class: "chips" });

    const form = el("form", { class: "ask" }) as HTMLFormElement;
    this.input = el("textarea", { rows: "1", placeholder: this.t.placeholder, "aria-label": this.t.placeholder, maxlength: "600" });
    this.sendBtn = el("button", { type: "submit", "aria-label": this.t.send }, ICON_SEND);
    form.append(this.input, this.sendBtn);
    form.addEventListener("submit", (e) => {
      e.preventDefault();
      this.ask(this.input.value);
    });
    this.input.addEventListener("keydown", (e) => {
      if (e.key === "Enter" && !e.shiftKey) {
        e.preventDefault();
        this.ask(this.input.value);
      }
    });
    this.input.addEventListener("input", () => {
      this.input.style.height = "auto";
      this.input.style.height = `${Math.min(this.input.scrollHeight, 110)}px`;
    });

    const foot = el("div", { class: "foot" });
    const note = el("span");
    note.textContent = this.t.aiNote;
    const human = el("button", { type: "button" });
    human.textContent = this.t.human;
    human.addEventListener("click", () => this.showHandoff());
    foot.append(note, human);

    panel.append(head, this.msgs, this.chips, form, foot);
    panel.addEventListener("keydown", (e) => {
      if (e.key === "Escape") this.toggle();
    });
    this.root.appendChild(panel);
    this.panel = panel;

    this.addBubble("bot", this.config.welcome);
    for (const m of this.history) this.addBubble(m.role, m.text, m.sources, m.products);
    this.renderChips();
  }

  private renderChips() {
    this.chips.innerHTML = "";
    if (this.history.length) return;
    for (const s of this.config.suggestions) {
      const b = el("button", { type: "button" });
      b.textContent = s;
      b.addEventListener("click", () => this.ask(s));
      this.chips.appendChild(b);
    }
  }

  // ---------------------------------------------------------- messages

  private addBubble(role: "user" | "bot", text: string, sources?: Source[], products?: Product[]): HTMLDivElement {
    const bubble = el("div", { class: `msg ${role}` });
    if (role === "bot") bubble.innerHTML = renderText(text);
    else bubble.textContent = text;
    this.msgs.appendChild(bubble);
    this.addExtras(sources, products);
    this.scroll();
    return bubble;
  }

  /** Product cards, then links to the pages used (minus pages already shown as a card). */
  private addExtras(sources: Source[] = [], products: Product[] = []) {
    const abs = (u: string) => new URL(u, window.location.href).href;
    if (products.length) this.addProducts(products);
    const cardUrls = new Set(products.filter((p) => p.url).map((p) => abs(p.url!)));
    const rest = sources.filter((s) => !cardUrls.has(abs(s.url)));
    if (rest.length) this.addSources(rest);
  }

  private formatPrice(p: Product): string {
    const n = Number(p.price);
    if (p.price && p.currency && !Number.isNaN(n)) {
      try {
        return new Intl.NumberFormat(this.config.language === "en" ? "en-GB" : "fr-FR", { style: "currency", currency: p.currency }).format(n);
      } catch {
        /* unknown currency code: show it as written */
      }
    }
    return [p.price, p.currency].filter(Boolean).join(" ");
  }

  private addProducts(products: Product[]) {
    const wrap = el("div", { class: "cards" });
    for (const p of products) {
      const card = el("a", { class: "card", href: p.url ? new URL(p.url, window.location.href).href : "#" });
      if (p.image) {
        const img = el("img", { src: new URL(p.image, window.location.href).href, alt: "", loading: "lazy" });
        card.appendChild(img);
      }
      const info = el("span", { class: "info" });
      const name = el("span", { class: "name" });
      name.textContent = p.name;
      info.appendChild(name);
      const price = this.formatPrice(p);
      if (price) {
        const pr = el("span", { class: "price" });
        pr.textContent = price;
        info.appendChild(pr);
      }
      const cta = el("span", { class: "cta" });
      cta.textContent = `${this.t.viewProduct} →`;
      info.appendChild(cta);
      card.appendChild(info);
      wrap.appendChild(card);
    }
    this.msgs.appendChild(wrap);
  }

  private addSources(sources: Source[]) {
    const wrap = el("div", { class: "sources" });
    for (const s of sources) {
      const a = el("a", { href: new URL(s.url, window.location.href).href });
      a.textContent = s.title;
      wrap.appendChild(a);
    }
    this.msgs.appendChild(wrap);
  }

  private scroll() {
    this.msgs.scrollTop = this.msgs.scrollHeight;
  }

  private async ask(raw: string) {
    const question = raw.trim();
    if (!question || this.busy) return;
    this.busy = true;
    this.sendBtn.disabled = true;
    this.input.value = "";
    this.input.style.height = "auto";
    this.chips.innerHTML = "";

    this.addBubble("user", question);
    this.history.push({ role: "user", text: question });
    const typing = el("div", { class: "msg bot typing", "aria-label": "…" }, "<span></span><span></span><span></span>");
    this.msgs.appendChild(typing);
    this.scroll();

    let bubble: HTMLDivElement | null = null;
    let text = "";
    let sources: Source[] = [];
    let products: Product[] = [];
    let handoff = false;
    try {
      const res = await fetch(`${this.api}/api/chat`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ site_id: this.siteId, message: question, conversation_id: this.conversationId, page_url: window.location.href }),
      });
      if (!res.ok || !res.body) {
        const detail = await res.json().then((d) => d.detail).catch(() => null);
        throw new Error(typeof detail === "string" ? detail : this.t.error);
      }
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      let buffer = "";
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, { stream: true });
        let split;
        while ((split = buffer.indexOf("\n\n")) >= 0) {
          const block = buffer.slice(0, split);
          buffer = buffer.slice(split + 2);
          const event = block.match(/^event: (.*)$/m)?.[1];
          const data = JSON.parse(block.match(/^data: (.*)$/m)?.[1] || "{}");
          if (event === "start") {
            this.conversationId = data.conversation_id;
            sources = data.sources || [];
          } else if (event === "token") {
            if (!bubble) {
              typing.remove();
              bubble = this.addBubble("bot", "");
            }
            text += data.t;
            bubble.innerHTML = renderText(text);
            this.scroll();
          } else if (event === "products") {
            products = data.products || [];
          } else if (event === "done") {
            handoff = data.handoff;
          } else if (event === "error") {
            throw new Error(data.message || this.t.error);
          }
        }
      }
      typing.remove();
      if (!text) throw new Error(this.t.error);
      this.history.push({ role: "bot", text, sources, products });
      this.addExtras(sources, products);
      if (handoff) this.showHandoff(question);
      this.save();
    } catch (err) {
      typing.remove();
      const msg = err instanceof Error && err.message !== "Failed to fetch" ? err.message : this.t.error;
      const e = this.addBubble("bot", msg);
      e.classList.add("error");
      // Keep the failed question out of the history so a retry starts clean.
      if (!text) this.history.pop();
    } finally {
      this.busy = false;
      this.sendBtn.disabled = false;
      this.scroll();
      this.input.focus();
    }
  }

  // ---------------------------------------------------------- human handoff

  private showHandoff(prefill = "") {
    if (this.msgs.querySelector(".handoff")) return;
    const box = el("form", { class: "handoff" }) as HTMLFormElement;
    const title = el("strong");
    title.textContent = this.t.handoffTitle;
    const name = el("input", { placeholder: this.t.name, autocomplete: "name", maxlength: "120" });
    const email = el("input", { placeholder: this.t.email, type: "email", autocomplete: "email", required: "", maxlength: "200" });
    const message = el("textarea", { placeholder: this.t.message, maxlength: "2000" });
    message.value = prefill || [...this.history].reverse().find((m) => m.role === "user")?.text || "";
    const row = el("div", { class: "row" });
    const cancel = el("button", { type: "button", class: "btn ghost" });
    cancel.textContent = this.t.cancel;
    cancel.addEventListener("click", () => box.remove());
    const submit = el("button", { type: "submit", class: "btn" });
    submit.textContent = this.t.submit;
    const status = el("div", { class: "note", role: "status" });
    row.append(cancel, submit);
    box.append(title, name, email, message, status, row);

    box.addEventListener("submit", async (e) => {
      e.preventDefault();
      submit.disabled = true;
      status.textContent = "";
      try {
        const res = await fetch(`${this.api}/api/leads`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            site_id: this.siteId, conversation_id: this.conversationId, page_url: window.location.href,
            name: name.value, email: email.value, message: message.value,
          }),
        });
        if (!res.ok) {
          const detail = await res.json().then((d) => d.detail).catch(() => null);
          throw new Error(res.status === 400 ? this.t.invalidEmail : typeof detail === "string" ? detail : this.t.error);
        }
        box.replaceWith(Object.assign(el("div", { class: "msg bot" }), { textContent: this.t.thanks }));
        this.scroll();
      } catch (err) {
        status.textContent = err instanceof Error ? err.message : this.t.error;
        submit.disabled = false;
      }
    });
    this.msgs.appendChild(box);
    this.scroll();
    name.focus();
  }
}

// ------------------------------------------------------------ boot

(() => {
  const script = (document.currentScript as HTMLScriptElement | null) ?? document.querySelector<HTMLScriptElement>("script[data-site]");
  const siteId = script?.dataset.site;
  if (!script || !siteId) {
    console.warn('[site-assistant] add data-site="your-site-id" to the widget script tag');
    return;
  }
  const api = (script.dataset.api || new URL(script.src, window.location.href).origin).replace(/\/$/, "");
  const boot = () => new SiteAssistant(api, siteId, script.dataset.teaser === "true", script.dataset.theme || "light").start(script.dataset.color);
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
})();
