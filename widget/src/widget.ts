/**
 * Site Assistant: embeddable AI chat widget.
 *
 *   <script src="https://YOUR-SERVER/widget.js" data-site="your-site-id" defer></script>
 *
 * Optional attributes: data-api (server URL, defaults to where widget.js is
 * served from), data-teaser="true" (shows a small invitation bubble) and
 * data-theme="light" | "dark" | "auto" (default light) and data-color="#hex"
 * (button colour before the site settings have loaded).
 */
import { css } from "./styles";

interface SiteConfig {
  id: string;
  name: string;
  language: string;
  color: string;
  welcome: string;
  suggestions: string[];
}

interface Source {
  title: string;
  url: string;
}

interface Product {
  name: string;
  price: string | null;
  currency: string | null;
  image: string | null;
  url: string | null;
}

interface StoredMessage {
  role: "user" | "bot";
  text: string;
  sources?: Source[];
  products?: Product[];
}

